const { expect, assert, fs, path } = require('./smoke-harness.cjs')
const FUTURE_YEAR = new Date().getFullYear() + 4

async function profileCategoriesThemes(h) {
  await h.nav('Settings')
  await h.field('Name').fill('Review household')
  await h.button('🦊').click()
  await h.field('Gross annual salary').fill('96000')
  await h.field('Withheld for taxes (%)').fill('25')
  await h.button('Save profile').click()
  await h.saved((d) => d.profile.name === 'Review household' && d.profile.annualSalary === 96000)
  await expect(h.page.getByText('Estimated take-home:', { exact: false })).toContainText('$6,000.00')
  await h.field('Method of measurement').selectOption('hourly')
  await h.field('Hourly rate').fill('50')
  await h.field('Hours per week').fill('40')
  await h.button('Save profile').click()
  await h.saved((d) => d.profile.incomeMethod === 'hourly' && d.profile.hourlyRate === 50)
  await expect(h.page.getByText('Estimated take-home:', { exact: false })).toContainText('$6,500.00')
  for (const basis of ['recorded', 'estimate-plus-extra', 'estimate']) {
    await h.field('Dashboard income basis').selectOption(basis)
    await h.button('Save profile').click()
    await h.saved((d) => d.profile.incomeBasis === basis)
  }

  await h.field('Name').fill('Temporary profile name')
  await h.button('Save profile').click()
  await h.saved((d) => d.profile.name === 'Temporary profile name')
  await h.undo()
  await expect(h.field('Name')).toHaveValue('Review household')

  // Theme changes are immediate, but must not implicitly save other profile drafts.
  await h.field('Name').fill('Unsaved name')
  const themes = h.page.locator('.theme-swatch')
  const count = await themes.count()
  assert.ok(count >= 2)
  const seen = new Set()
  for (let i = 0; i < count; i++) {
    await themes.nth(i).click()
    await expect(themes.nth(i)).toHaveAttribute('aria-pressed', 'true')
    await expect.poll(async () => {
      const data = await h.data()
      return data.profile.themeId === await h.page.locator('html').getAttribute('data-theme')
    }).toBe(true)
    const data = await h.data()
    assert.equal(data.profile.name, 'Review household')
    seen.add(data.profile.themeId)
  }
  assert.equal(seen.size, count, 'Every available theme must persist and apply')
  await expect(h.field('Name')).toHaveValue('Unsaved name')
  await h.nav('Dashboard')
  await h.nav('Settings')
  await expect(h.field('Name')).toHaveValue('Review household')
  await h.field('Method of measurement').selectOption('salary')
  await h.button('Save profile').click()
  await h.saved((d) => d.profile.incomeMethod === 'salary')

  await h.page.getByPlaceholder('New category name').fill('QA category')
  await h.button('Add category').click()
  await h.saved((d) => d.categories.some((c) => c.name === 'QA category'))
  await h.holdFirstIpc('category:upsert')
  try {
    await h.field('Category name: QA category').fill('Pending category name')
    await h.field('Name').focus()
    await h.waitForHeldIpc()
    await h.field('Category name: QA category').fill('QA category')
    await h.field('Name').focus()
  } finally {
    await h.releaseIpc()
  }
  await expect(h.page.getByRole('button', { name: /Undo last change/ })).toBeEnabled()
  assert.ok((await h.data()).categories.some((c) => c.name === 'QA category'), 'Reverting a pending category edit must queue the final value')
  await h.undo()
  await expect(h.field('Category name: Pending category name')).toHaveValue('Pending category name')
  await h.undo()
  await expect(h.field('Category name: QA category')).toHaveValue('QA category')
  await h.field('Category name: QA category').fill('QA edited')
  // Blur followed by another edit used to silently discard an autosave.
  await h.field('Monthly limit: QA category').fill('650.00')
  await h.field('Name').focus()
  await h.saved((d) => d.categories.some((c) => c.name === 'QA edited' && c.monthlyLimit === 650))
  await h.field('Monthly limit: QA edited').fill('200')
  await h.field('Name').focus()
  await h.saved((d) => d.categories.find((c) => c.name === 'QA edited').monthlyLimit === 200)
  await h.field('Monthly limit: QA edited').fill('200.00')
  await h.field('Name').focus()
  await expect(h.field('Monthly limit: QA edited')).toHaveValue('200')
  await h.undo()
  await expect(h.field('Monthly limit: QA edited')).toHaveValue('650')
  await h.field('Recurring category: QA edited').check()
  await h.saved((d) => d.categories.find((c) => c.name === 'QA edited').fixed)
  await h.undo()
  await expect(h.field('Recurring category: QA edited')).not.toBeChecked()
  await h.undo()
  await expect(h.field('Monthly limit: QA edited')).toHaveValue('0')
  await h.undo()
  await expect(h.field('Category name: QA category')).toHaveValue('QA category')
  await h.page.getByTitle('Delete QA category ($0.00)', { exact: true }).click()
  await h.saved((d) => !d.categories.some((c) => c.name === 'QA category'))
  await h.screenshot('settings')
}

