  await h.importCount(1)
  await csvDrop.dispose()
  await h.saved((d) => d.transactions.some((t) => t.description === 'Coffee kiosk' && t.kind === 'expense'))

  // Applying rules to old uncategorized rows is separate from automatic import categorization.
